// 1. Buat IF-ELSE untuk menentukan Grade nilai.
// A: 90-100, B: 80-89, C: 70-79, D: <70
let nilai = 85;

if (nilai >= 90) {
  console.log("Grade A");
} else if (nilai >= 80) {
  console.log("Grade B");
} else if (nilai >= 70) {
  console.log("Grade C");
} else {
  console.log("Grade D");
}

